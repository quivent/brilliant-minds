class QuestionCategory(Enum):
    """Categories for classifying evaluation questions."""
    ARCHITECTURE = "architecture"
    CODE_QUALITY = "code_quality"
    DOCUMENTATION = "documentation"
    TESTING = "testing"
    SECURITY = "security"
    PERFORMANCE = "performance"
    MAINTAINABILITY = "maintainability"
    INNOVATION = "innovation"
    METHODOLOGY = "methodology"
    PHILOSOPHY = "philosophy"
    OTHER = "other"

    @classmethod
    def from_string(cls, value: str) -> 'QuestionCategory':
        """Convert string to QuestionCategory, with fuzzy matching."""
        value_lower = value.lower().strip()

        # Direct match
        for category in cls:
            if category.value == value_lower:
                return category

        # Fuzzy matching based on keywords
        category_keywords = {
            cls.ARCHITECTURE: ['architecture', 'design', 'structure', 'system', 'component', 'module', 'pattern', 'layer'],
            cls.CODE_QUALITY: ['code quality', 'clean code', 'readability', 'style', 'convention', 'smell', 'refactor'],
            cls.DOCUMENTATION: ['documentation', 'docs', 'comment', 'readme', 'api doc', 'docstring'],
            cls.TESTING: ['test', 'testing', 'coverage', 'unit test', 'integration', 'e2e', 'tdd', 'bdd'],
            cls.SECURITY: ['security', 'vulnerability', 'auth', 'encryption', 'injection', 'xss', 'csrf'],
            cls.PERFORMANCE: ['performance', 'speed', 'latency', 'throughput', 'optimization', 'cache', 'memory', 'cpu'],
            cls.MAINTAINABILITY: ['maintainability', 'maintenance', 'technical debt', 'complexity', 'coupling', 'cohesion'],
            cls.INNOVATION: ['innovation', 'creative', 'novel', 'breakthrough', 'cutting-edge', 'state-of-the-art'],
            cls.METHODOLOGY: ['methodology', 'process', 'workflow', 'agile', 'practice', 'approach', 'strategy'],
            cls.PHILOSOPHY: ['philosophy', 'principle', 'belief', 'value', 'ethic', 'vision', 'mission'],
        }

        for category, keywords in category_keywords.items():
            for keyword in keywords:
                if keyword in value_lower:
                    return category

        return cls.OTHER


@dataclass
class Question:
    """
    Represents a single evaluation question generated by a brilliant mind.

    Attributes:
        id: Unique identifier for the question
        text: The actual question text
        category: Classification of the question type
        rationale: Why this question matters to this mind
        good_answer_indicators: Signs of a good answer
        bad_answer_indicators: Signs of a poor answer
        difficulty: Question difficulty level (1-5)
        weight: Importance weight for this mind (0.0-1.0)
        generated_by: Name of the mind that generated this question
    """
    id: str
    text: str
    category: QuestionCategory
    rationale: str
    good_answer_indicators: List[str]
    bad_answer_indicators: List[str]
    difficulty: int
    weight: float
    generated_by: str

    def __post_init__(self):
        """Validate question data after initialization."""
        if not 1 <= self.difficulty <= 5:
            raise ValueError(f"Difficulty must be between 1 and 5, got {self.difficulty}")
        if not 0.0 <= self.weight <= 1.0:
            raise ValueError(f"Weight must be between 0.0 and 1.0, got {self.weight}")
        if not self.text.strip():
            raise ValueError("Question text cannot be empty")
        if not self.id:
            self.id = self._generate_id()

    def _generate_id(self) -> str:
        """Generate a unique ID based on question content."""
        content = f"{self.text}:{self.generated_by}"
        return hashlib.sha256(content.encode()).hexdigest()[:12]

    def to_dict(self) -> Dict[str, Any]:
        """Convert question to dictionary representation."""
        return {
            "id": self.id,
            "text": self.text,
            "category": self.category.value,
            "rationale": self.rationale,
            "good_answer_indicators": self.good_answer_indicators,
            "bad_answer_indicators": self.bad_answer_indicators,
            "difficulty": self.difficulty,
            "weight": self.weight,
            "generated_by": self.generated_by
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> 'Question':
        """Create a Question from dictionary representation."""
        return cls(
            id=data.get("id", ""),
            text=data["text"],
            category=QuestionCategory.from_string(data["category"]) if isinstance(data["category"], str) else data["category"],
            rationale=data["rationale"],
            good_answer_indicators=data.get("good_answer_indicators", []),
            bad_answer_indicators=data.get("bad_answer_indicators", []),
            difficulty=data.get("difficulty", 3),
            weight=data.get("weight", 0.5),
            generated_by=data["generated_by"]
        )

    def similarity_hash(self) -> str:
        """Generate a hash for detecting similar questions."""
        # Normalize text for comparison
        normalized = re.sub(r'\s+', ' ', self.text.lower().strip())
        normalized = re.sub(r'[^\w\s]', '', normalized)
        words = sorted(set(normalized.split()))
        return hashlib.md5(' '.join(words).encode()).hexdigest()


@dataclass
class QuestionSet:
    """
    A collection of questions generated by a specific mind.

    Attributes:
        mind_name: Name of the brilliant mind that generated these questions
        questions: List of Question objects
        generation_context: Description of what project/research was considered
        metadata: Additional metadata about the generation process
    """
    mind_name: str
    questions: List[Question]
    generation_context: str
    metadata: Dict[str, Any] = field(default_factory=dict)

    def by_category(self) -> Dict[QuestionCategory, List[Question]]:
        """Group questions by their category."""
        grouped: Dict[QuestionCategory, List[Question]] = defaultdict(list)
        for question in self.questions:
            grouped[question.category].append(question)
        return dict(grouped)

    def by_weight(self, min_weight: float = 0.0) -> List[Question]:
        """Get questions filtered by minimum weight, sorted by weight descending."""
        filtered = [q for q in self.questions if q.weight >= min_weight]
        return sorted(filtered, key=lambda q: q.weight, reverse=True)

    def by_difficulty(self, min_difficulty: int = 1, max_difficulty: int = 5) -> List[Question]:
        """Get questions filtered by difficulty range."""
        return [q for q in self.questions
                if min_difficulty <= q.difficulty <= max_difficulty]

    def category_coverage(self) -> Dict[QuestionCategory, int]:
        """Get count of questions per category."""
        coverage = {cat: 0 for cat in QuestionCategory}
        for question in self.questions:
            coverage[question.category] += 1
        return coverage

    def diversity_score(self) -> float:
        """
        Calculate a diversity score (0-1) based on category distribution.
        Higher scores indicate better coverage across categories.
        """
        if not self.questions:
            return 0.0

        coverage = self.category_coverage()
        non_zero_categories = sum(1 for count in coverage.values() if count > 0)
        total_categories = len(QuestionCategory)

        # Also consider evenness of distribution
        total_questions = len(self.questions)
        expected_per_category = total_questions / total_categories
        variance = sum((count - expected_per_category) ** 2 for count in coverage.values())
        evenness = 1.0 / (1.0 + (variance / total_categories))

        coverage_score = non_zero_categories / total_categories
        return (coverage_score + evenness) / 2

    def to_json(self, path: str) -> None:
        """Save the question set to a JSON file."""
        data = {
            "mind_name": self.mind_name,
            "generation_context": self.generation_context,
            "metadata": self.metadata,
            "questions": [q.to_dict() for q in self.questions],
            "statistics": {
                "total_questions": len(self.questions),
                "category_coverage": {k.value: v for k, v in self.category_coverage().items()},
                "diversity_score": self.diversity_score(),
                "average_difficulty": sum(q.difficulty for q in self.questions) / len(self.questions) if self.questions else 0,
                "average_weight": sum(q.weight for q in self.questions) / len(self.questions) if self.questions else 0
            }
        }

        path_obj = Path(path)
        path_obj.parent.mkdir(parents=True, exist_ok=True)

        with open(path, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=2, ensure_ascii=False)

    @classmethod
    def from_json(cls, path: str) -> 'QuestionSet':
        """Load a question set from a JSON file."""
        with open(path, 'r', encoding='utf-8') as f:
            data = json.load(f)

        questions = [Question.from_dict(q) for q in data.get("questions", [])]

        return cls(
            mind_name=data["mind_name"],
            questions=questions,
            generation_context=data.get("generation_context", ""),
            metadata=data.get("metadata", {})
        )

    def merge(self, other: 'QuestionSet', deduplicate: bool = True) -> 'QuestionSet':
        """Merge another question set into this one."""
        combined_questions = self.questions + other.questions

        if deduplicate:
            seen_hashes: Set[str] = set()
            unique_questions = []
            for q in combined_questions:
                h = q.similarity_hash()
                if h not in seen_hashes:
                    seen_hashes.add(h)
                    unique_questions.append(q)
            combined_questions = unique_questions

        return QuestionSet(
            mind_name=f"{self.mind_name} + {other.mind_name}",
            questions=combined_questions,
            generation_context=f"Merged: {self.generation_context} | {other.generation_context}",
            metadata={
                "merged_from": [self.mind_name, other.mind_name],
                "original_counts": [len(self.questions), len(other.questions)]
            }
        )


@dataclass
class ProjectInfo:
    """
    Information about a project being evaluated.

    Attributes:
        name: Project name
        description: Brief description of the project
        type: Type of project (repository, research, paper, product)
        domain: Domain area (ai, systems, web, etc.)
        key_technologies: List of main technologies used
        goals: List of project goals/objectives
        additional_context: Any extra context for question generation
    """
    name: str
    description: str
    type: str  # "repository", "research", "paper", "product"
    domain: str  # "ai", "systems", "web", etc.
    key_technologies: List[str]
    goals: List[str]
    additional_context: Dict[str, Any] = field(default_factory=dict)

    def to_prompt_context(self) -> str:
        """Generate a prompt-friendly context string."""
        context_parts = [
            f"Project: {self.name}",
            f"Type: {self.type}",
            f"Domain: {self.domain}",
            f"Description: {self.description}",
            "",
            "Key Technologies:",
        ]

        for tech in self.key_technologies:
            context_parts.append(f"  - {tech}")

        context_parts.append("")
        context_parts.append("Goals:")

        for goal in self.goals:
            context_parts.append(f"  - {goal}")

        if self.additional_context:
            context_parts.append("")
            context_parts.append("Additional Context:")
            for key, value in self.additional_context.items():
                if isinstance(value, list):
                    context_parts.append(f"  {key}:")
                    for item in value:
                        context_parts.append(f"    - {item}")
                else:
                    context_parts.append(f"  {key}: {value}")

        return "\n".join(context_parts)

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary representation."""
        return {
            "name": self.name,
            "description": self.description,
            "type": self.type,
            "domain": self.domain,
            "key_technologies": self.key_technologies,
            "goals": self.goals,
            "additional_context": self.additional_context
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> 'ProjectInfo':
        """Create ProjectInfo from dictionary."""
        return cls(
            name=data["name"],
            description=data["description"],
            type=data["type"],
            domain=data["domain"],
            key_technologies=data.get("key_technologies", []),
            goals=data.get("goals", []),
            additional_context=data.get("additional_context", {})
        )


