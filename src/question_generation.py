def merge_question_sets(*question_sets: QuestionSet) -> QuestionSet:
    """
    Merge multiple question sets into one, removing duplicates.

    Args:
        *question_sets: QuestionSet objects to merge

    Returns:
        A merged QuestionSet
    """
    if not question_sets:
        raise ValueError("At least one question set is required")

    result = question_sets[0]
    for qs in question_sets[1:]:
        result = result.merge(qs, deduplicate=True)

    return result


def load_question_sets_from_directory(directory: str) -> List[QuestionSet]:
    """
    Load all question sets from a directory.

    Args:
        directory: Path to directory containing JSON question set files

    Returns:
        List of QuestionSet objects
    """
    dir_path = Path(directory)
    question_sets = []

    for json_file in dir_path.glob("*.json"):
        try:
            qs = QuestionSet.from_json(str(json_file))
            question_sets.append(qs)
        except (json.JSONDecodeError, KeyError, ValueError) as e:
            # Skip malformed files
            continue

    return question_sets


def export_questions_to_markdown(question_set: QuestionSet, path: str) -> None:
    """
    Export a question set to a readable Markdown format.

    Args:
        question_set: The question set to export
        path: Output file path
    """
    lines = [
        f"# Evaluation Questions by {question_set.mind_name}",
        "",
        f"**Context**: {question_set.generation_context}",
        "",
        f"**Total Questions**: {len(question_set.questions)}",
        f"**Diversity Score**: {question_set.diversity_score():.2f}",
        "",
        "---",
        "",
    ]

    by_category = question_set.by_category()

    for category in QuestionCategory:
        questions = by_category.get(category, [])
        if questions:
            lines.append(f"## {category.value.replace('_', ' ').title()}")
            lines.append("")

            for i, q in enumerate(questions, 1):
                lines.append(f"### {i}. {q.text}")
                lines.append("")
                lines.append(f"**Difficulty**: {'*' * q.difficulty} ({q.difficulty}/5)")
                lines.append(f"**Weight**: {q.weight:.2f}")
                lines.append("")
                lines.append(f"**Rationale**: {q.rationale}")
                lines.append("")
                lines.append("**Good Answer Indicators**:")
                for indicator in q.good_answer_indicators:
                    lines.append(f"- {indicator}")
                lines.append("")
                lines.append("**Bad Answer Indicators**:")
                for indicator in q.bad_answer_indicators:
                    lines.append(f"- {indicator}")
                lines.append("")
                lines.append("---")
                lines.append("")

    path_obj = Path(path)
    path_obj.parent.mkdir(parents=True, exist_ok=True)

    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
