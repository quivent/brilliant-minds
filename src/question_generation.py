"""
Question Generation Engine

Enables restored brilliant minds to generate evaluation questions
based on their unique expertise and values.

This module provides:
- Question and QuestionSet data classes for structured question management
- QuestionGenerator for AI-powered question generation from a mind's perspective
- Project information helpers for context-aware generation
- Quality filtering and diversity assurance mechanisms
"""

